class OutputFormatter:

    def format_attributes(self, attributes: list) -> dict:
        output = {}
        for index in range(1, 51):
            output[f"ATTRIBUTE_LABEL {index}"] = ""
            output[f"ATTRIBUTE_VALUE {index}"] = ""
            output[f"ATTRIBUTE_UOM {index}"] = ""

        if isinstance(attributes, list):
            for index, attr in enumerate(attributes[:50], start=1):
                if isinstance(attr, dict):
                    output[f"ATTRIBUTE_LABEL {index}"] = attr.get("label") or ""
                    output[f"ATTRIBUTE_VALUE {index}"] = str(attr.get("value")) if attr.get("value") is not None else ""
                    output[f"ATTRIBUTE_UOM {index}"] = attr.get("uom") or ""

        return output

    def format_product(self, product: dict, raw_input: dict | None = None, rag_fields: dict | None = None) -> dict:
        raw = raw_input or {}
        rag = rag_fields or {}
        
        identity = product.get("identity") or {}
        mfr_res = identity.get("manufacturer") or {}
        brand_res = identity.get("brand") or {}
        mpn = identity.get("mpn") or raw.get("Mfg_Part_Num") or product.get("product_id") or ""

        classification = product.get("classification") or {}
        dept = classification.get("department") or ""
        cls_name = classification.get("class_name") or ""
        fine = classification.get("fine") or ""
        classpath = classification.get("classpath") or ""

        understanding = product.get("understanding") or {}
        product_name = fine or understanding.get("product_type") or "Hardware & Tools"

        mfr_name = mfr_res.get("canonical_value") or raw.get("Part_Manuf") or ""
        brand_name = brand_res.get("canonical_value") or raw.get("E1_Brand") or raw.get("Unilog_Brand") or raw.get("DIB_Brand") or ""
        part_desc = raw.get("Part_Desc") or ""

        # Descriptions constructed from available evidence
        mobile_desc = f"{mfr_name} {brand_name}, {product_name}, {mpn}".strip(", ")
        invoice_desc = part_desc.upper() if part_desc else mpn
        short_desc = f"{brand_name} {mpn} {product_name}".strip()
        long_desc = part_desc

        web_disc = product.get("web_discovery") or {}

        # Build output dict with all keys initialized to ""
        out = {col: "" for col in COLUMN_ORDER}

        # 1. Fill base derived / raw values
        out["MFR URL"] = web_disc.get("mfr_url") or ""
        ref_urls = web_disc.get("ref_urls") or []
        for i in range(1, 6):
            if i <= len(ref_urls):
                out[f"Ref URL {i}"] = ref_urls[i - 1]

        out["PART_NUMBER"] = mpn
        out["Dept"] = dept
        out["Class"] = cls_name
        out["Fine"] = fine
        out["SKU - MY_PART_NUMBER"] = mpn
        out["Mfg_Part_Num"] = raw.get("Mfg_Part_Num") or mpn
        out["Part_Desc"] = part_desc
        out["E1_Brand"] = raw.get("E1_Brand") or ""
        out["Unilog_Brand"] = raw.get("Unilog_Brand") or ""
        out["DIB_Brand"] = raw.get("DIB_Brand") or ""
        out["Part_Manuf"] = raw.get("Part_Manuf") or ""

        out["MANUFACTURER_NAME"] = mfr_name
        out["BRAND_NAME"] = brand_name
        out["MANUFACTURER_PART_NUMBER"] = mpn
        out["Classpath"] = classpath

        out["MOBILE_DESC"] = mobile_desc
        out["INVOICE_DESC"] = invoice_desc
        out["SHORT_DESC"] = short_desc
        out["LONG_DESC1"] = long_desc
        out["RETAIL_DESC"] = short_desc
        out["Product Name"] = product_name

        # Structured attributes (1..50)
        attr_dict = self.format_attributes(product.get("attributes") or [])
        out.update(attr_dict)

        # Physical / Spec attributes from structured_attributes or attributes array
        struct_attrs = product.get("structured_attributes") or {}

        def _get_val_uom(attr_name):
            val_full = struct_attrs.get(attr_name)
            if not val_full and isinstance(product.get("attributes"), list):
                for a in product["attributes"]:
                    if isinstance(a, dict) and a.get("label", "").upper() == attr_name:
                        v = a.get("value")
                        u = a.get("uom")
                        return (str(v) if v is not None else "", u or "")
            if val_full:
                parts = str(val_full).split(maxsplit=1)
                if len(parts) == 2:
                    return parts[0], parts[1]
                return str(val_full), ""
            return "", ""

        for dim in ["LENGTH", "HEIGHT", "WIDTH", "WEIGHT", "VOLUME"]:
            v, u = _get_val_uom(dim)
            out[dim] = v
            out[f"{dim}_UOM"] = u

        out["UPC"] = struct_attrs.get("UPC") or ""
        out["GTIN"] = struct_attrs.get("GTIN") or ""
        out["UNSPSC"] = struct_attrs.get("UNSPSC") or ""

        # Media & documents
        out["Product Image"] = web_disc.get("product_image") or ""
        alt_imgs = web_disc.get("alternate_images") or []
        for i in range(1, 5):
            if i <= len(alt_imgs):
                out[f"Alternate Image {i}"] = alt_imgs[i - 1]

        out["Specification Sheet"] = web_disc.get("specification_sheet") or ""
        out["Instruction/Installation Manual"] = web_disc.get("manual") or ""

        if out["Product Image"]:
            out["Actual Image (Yes/No)"] = "Yes"

        # 2. Priority Override from RAG Evidence fields when present
        if rag:
            for k in COLUMN_ORDER:
                v = rag.get(k)
                if v and str(v).strip() and str(v).strip().lower() not in {'none', 'null', 'n/a'}:
                    out[k] = str(v).strip()

        return out